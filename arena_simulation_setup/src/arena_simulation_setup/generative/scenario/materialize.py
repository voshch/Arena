"""Writing base scenario directories and pruning generated ones. Only files carrying `GENERATED_MARKER` are replaced."""

from __future__ import annotations

import os
import shutil
import tempfile
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from arena_simulation_setup.generative.core.generated import GENERATED_MARKER

from .formats import scenario_text
from .populate import bt_type_source


def is_generated(path: Path) -> bool:
    try:
        return GENERATED_MARKER in path.read_text()[:1200]
    except OSError:
        return False


class WouldOverwrite(Exception):
    pass


def write_base(
    doc: dict[str, Any],
    *,
    world_root: str | os.PathLike[str],
    profile: str,
    force: bool = False,
    note: str = "",
) -> Path:
    """Write `scenarios/<profile>/scenario.yaml`, refusing to replace a hand-authored scenario unless `force`."""
    out = Path(world_root) / "scenarios" / profile
    existing = out / "scenario.yaml"
    if existing.is_file() and not force and not is_generated(existing):
        raise WouldOverwrite(f"{existing} already exists and was not generated by this tool. Pass force=True to replace it, or generate under a different name.")
    src = bt_type_source()
    local = src.is_file() and any(str((a.get("agent") or {}).get("agent_type", "")).startswith("./") for a in (doc.get("humans") or []))
    n = len(doc.get("humans") or [])
    header = "\n".join(
        (
            f"# Base scenario: {profile} ({n} pedestrian{'s' if n != 1 else ''})",
            "# generator: populate",
            *([f"# {note}"] if note else []),
            "#",
            GENERATED_MARKER,
            "",
            "",
        )
    )
    with tempfile.TemporaryDirectory() as stage:
        if local:
            shutil.copy2(src, Path(stage) / src.name)
        try:
            text = scenario_text(doc, world_root=Path(world_root), types_dir=Path(stage), header=header)
        except ValueError as exc:
            raise ValueError(f"{out}: {exc}") from exc
    out.mkdir(parents=True, exist_ok=True)
    if local:
        shutil.copy2(src, out / src.name)
    (out / "scenario.yaml").write_text(text)
    return out


def prune_generated(world_root: str | os.PathLike[str], keep: Sequence[str]) -> list[str]:
    root = Path(world_root) / "scenarios"
    wanted = set(keep)
    gone: list[str] = []
    for path in sorted(root.glob("*/scenario.yaml")):
        name = path.parent.name
        if name in wanted or not is_generated(path):
            continue
        shutil.rmtree(path.parent)
        gone.append(name)
    return gone
