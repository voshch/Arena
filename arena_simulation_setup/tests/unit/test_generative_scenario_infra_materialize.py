from __future__ import annotations

import shutil
from pathlib import Path

import pytest
from arena_simulation_setup.generative.scenario.cli import main
from arena_simulation_setup.generative.core.generated import GENERATED_MARKER
from arena_simulation_setup.generative.scenario.materialize import WouldOverwrite, is_generated, prune_generated, write_base

SHIPPED = Path(__file__).resolve().parents[2] / "worlds"
HAND = "format: arena-scenario/2\nhumans: []\n"


def _world(tmp_path: Path) -> Path:
    world = tmp_path / "worlds" / "sbend"
    world.mkdir(parents=True)
    shutil.copy(SHIPPED / "sbend_corridor" / "world.yaml", world / "world.yaml")
    return world


def _scenario(world: Path, name: str, text: str) -> Path:
    path = world / "scenarios" / name / "scenario.yaml"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    return path


def _populate(world: Path, capsys: pytest.CaptureFixture[str], *extra: str) -> str:
    assert main(["populate", world.name, "--worlds", str(world.parent), "--write", *extra]) == 0
    return capsys.readouterr().out


def test_a_hand_authored_base_is_skipped_and_kept(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    world = _world(tmp_path)
    hand = _scenario(world, "normal", HAND)
    out = _populate(world, capsys)
    assert "normal  SKIPPED" in out and "was not generated by this tool" in out
    assert hand.read_text() == HAND
    assert all(is_generated(world / "scenarios" / profile / "scenario.yaml") for profile in ("break", "night", "empty"))


def test_force_replaces_a_hand_authored_base(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    world = _world(tmp_path)
    hand = _scenario(world, "normal", HAND)
    _populate(world, capsys, "--force")
    assert GENERATED_MARKER in hand.read_text()


def test_write_base_refuses_a_hand_authored_scenario_and_replaces_a_generated_one(tmp_path: Path) -> None:
    world = _world(tmp_path)
    hand = _scenario(world, "mine", HAND)
    with pytest.raises(WouldOverwrite, match="was not generated by this tool"):
        write_base({"humans": []}, world_root=world, profile="mine")
    assert hand.read_text() == HAND
    generated = _scenario(world, "old", f"{GENERATED_MARKER}\nhumans: []\n")
    write_base({"humans": []}, world_root=world, profile="old", note="rewritten")
    assert "# rewritten" in generated.read_text()


def test_prune_removes_only_stale_generated_bases(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    world = _world(tmp_path)
    mine = _scenario(world, "mine", HAND)
    stale = _scenario(world, "stale", f"{GENERATED_MARKER}\nhumans: []\n")
    case = _scenario(world, "normal__u_001", f"{GENERATED_MARKER}\nhumans: []\n")
    out = _populate(world, capsys, "--prune")
    assert "pruned stale generated base stale" in out
    assert not stale.parent.exists()
    assert mine.read_text() == HAND and case.is_file()
    assert all(is_generated(world / "scenarios" / profile / "scenario.yaml") for profile in ("normal", "break", "night", "empty"))


def test_prune_generated_keeps_the_named_and_the_hand_authored(tmp_path: Path) -> None:
    world = _world(tmp_path)
    _scenario(world, "mine", HAND)
    for name in ("kept", "gone"):
        _scenario(world, name, f"{GENERATED_MARKER}\nhumans: []\n")
    assert prune_generated(world, ["kept"]) == ["gone"]
    assert sorted(p.name for p in (world / "scenarios").iterdir()) == ["kept", "mine"]
